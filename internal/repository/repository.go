// ActiveAccount represents an account eligible for scheduled sync or PSD2 consent expiry checks.
type ActiveAccount struct {
	ID                      string
	UserID                  string
	IBAN                    string
	GoCardlessRequisitionID string
	GoCardlessAccountID     string
	Status                  string
	BalanceCents            int64
	AccessExpiresAt         time.Time
	LastSyncAt              time.Time
	RemainingCalls          int
	TransactionsRateLimits  gocardless.RateLimitHeaders
	BalancesRateLimits      gocardless.RateLimitHeaders
}

// ClassifiedTransaction pairs an incoming transaction with its 3-tier classification and internal-transfer flag.
type ClassifiedTransaction struct {
	Incoming           dedup.IncomingTransaction
	CategoryID         *string
	CategorySource     *string
	IsInternalTransfer bool
}

// SyncOutcome holds all changes to persist atomically in a single MongoDB ACID session after a sync.
type SyncOutcome struct {
	SyncID                 string
	UserID                 string
	AccountID              string
	BalanceCents           int64
	TransactionsFetched    int
	TransactionsRateLimits gocardless.RateLimitHeaders
	BalancesRateLimits     gocardless.RateLimitHeaders
	NewTransactions        []ClassifiedTransaction
	PromotedPendingToBook  map[string]ClassifiedTransaction
	IncrementedPendingIDs  []string
	DeletedPendingIDs      []string
	CompletedAt            time.Time
}

// BudgetRecord represents an active monthly budget in integer cents.
type BudgetRecord struct {
	ID         string
	UserID     string
	CategoryID string
	Amount     int64
}

// AlertRecord represents a deduplicated system alert generated by the worker.
type AlertRecord struct {
	ID        string
	UserID    string
	BudgetID  *string
	AccountID *string
	Type      string // budget_threshold, budget_exceeded, account_consent_expiring, account_expired
	Period    string // YYYY-MM
	Message   string
	Metadata  map[string]any
	CreatedAt time.Time
}

// CategorySummaryItem holds pre-aggregated spending per category in integer cents.
type CategorySummaryItem struct {
	CategoryID string
	TotalCents int64
	Count      int
}

// SpendingSummaryRecord represents a pre-aggregated monthly spending summary for a user.
type SpendingSummaryRecord struct {
	UserID        string
	Period        string // YYYY-MM
	TotalIncome   int64
	TotalExpenses int64
	ByCategory    []CategorySummaryItem
	UpdatedAt     time.Time
}

// UncategorizedTransaction represents a booked transaction with category_id == nil to be retried by Jev.
type UncategorizedTransaction struct {
	ID          string
	UserID      string
	AccountID   string
	Date        time.Time
	Description string
	Creditor    string
	AmountCents int64
}

// WorkerStore defines all persistence operations required by backend-worker.
type WorkerStore interface {
	ListActiveAccounts(ctx context.Context) ([]ActiveAccount, error)
	GetAccount(ctx context.Context, accountID string) (*ActiveAccount, error)
	MarkAccountExpired(ctx context.Context, accountID string) error
	ListUserIBANs(ctx context.Context, userID string) (map[string]bool, error)
	ListAccountTransactions(ctx context.Context, accountID string) ([]dedup.StoredTransaction, error)
	ListManualRules(ctx context.Context, userID string) (map[string]string, error)
	ListCategories(ctx context.Context) ([]ai.CategoryOption, error)
	ApplySyncOutcome(ctx context.Context, outcome SyncOutcome) error
	MarkSyncFailed(ctx context.Context, syncID string, errCode int, errDetail string) error
	EvaluateAndCreateBudgetAlerts(ctx context.Context, userID, period string) ([]AlertRecord, error)
	CreateConsentAlert(ctx context.Context, userID, accountID, alertType, period, message string) (*AlertRecord, bool, error)
	ListUncategorizedBooked(ctx context.Context) ([]UncategorizedTransaction, error)
	ApplyRetriedCategories(ctx context.Context, updates map[string]ai.ClassificationResult) error
}

// MemoryWorkerStore is a thread-safe in-memory implementation of WorkerStore for tests and local runs.
type MemoryWorkerStore struct {
	mu           sync.RWMutex
	accounts     map[string]*ActiveAccount
	transactions map[string]*storedTxRecord
	categories   []ai.CategoryOption
	summaries    map[string]*SpendingSummaryRecord // userID + "|" + period
	budgets      map[string]*BudgetRecord
	alerts       map[string]*AlertRecord
	syncStatuses map[string]string
}

type storedTxRecord struct {
	dedup.StoredTransaction
	UserID    string
	AccountID string
}

