func genID() string {
	b := make([]byte, 12)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

func (s *MemoryWorkerStore) SeedAccount(acc ActiveAccount) {
	s.mu.Lock()
	defer s.mu.Unlock()
	cp := acc
	s.accounts[acc.ID] = &cp
}

func (s *MemoryWorkerStore) SeedTransaction(userID, accountID string, tx dedup.StoredTransaction) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if tx.ID == "" {
		tx.ID = genID()
	}
	s.transactions[tx.ID] = &storedTxRecord{
		StoredTransaction: tx,
		UserID:            userID,
		AccountID:         accountID,
	}
}

func (s *MemoryWorkerStore) SeedBudget(b BudgetRecord) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if b.ID == "" {
		b.ID = genID()
	}
	cp := b
	s.budgets[b.ID] = &cp
}

func (s *MemoryWorkerStore) GetSpendingSummary(userID, period string) *SpendingSummaryRecord {
	s.mu.RLock()
	defer s.mu.RUnlock()
	sum, ok := s.summaries[userID+"|"+period]
	if !ok {
		return nil
	}
	cp := *sum
	cp.ByCategory = append([]CategorySummaryItem(nil), sum.ByCategory...)
	return &cp
}

func (s *MemoryWorkerStore) ListActiveAccounts(_ context.Context) ([]ActiveAccount, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	var out []ActiveAccount
	for _, acc := range s.accounts {
		if acc.Status == "enabled" {
			out = append(out, *acc)
		}
	}
	return out, nil
}

func (s *MemoryWorkerStore) GetAccount(_ context.Context, accountID string) (*ActiveAccount, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	acc, ok := s.accounts[accountID]
	if !ok {
		return nil, fmt.Errorf("account %s not found", accountID)
	}
	cp := *acc
	return &cp, nil
}

func (s *MemoryWorkerStore) MarkAccountExpired(_ context.Context, accountID string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if acc, ok := s.accounts[accountID]; ok {
		acc.Status = "expired"
	}
	return nil
}

func (s *MemoryWorkerStore) ListUserIBANs(_ context.Context, userID string) (map[string]bool, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	ibans := make(map[string]bool)
	for _, acc := range s.accounts {
		if acc.UserID == userID && acc.IBAN != "" {
			norm := strings.ToUpper(strings.ReplaceAll(strings.TrimSpace(acc.IBAN), " ", ""))
			ibans[norm] = true
		}
	}
	return ibans, nil
}

func (s *MemoryWorkerStore) ListAccountTransactions(_ context.Context, accountID string) ([]dedup.StoredTransaction, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	var out []dedup.StoredTransaction
	for _, tx := range s.transactions {
		if tx.AccountID == accountID {
			out = append(out, tx.StoredTransaction)
		}
	}
	return out, nil
}

func (s *MemoryWorkerStore) ListManualRules(_ context.Context, userID string) (map[string]string, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	rules := make(map[string]string)
	for _, tx := range s.transactions {
		if tx.UserID == userID && tx.CategorySource != nil && *tx.CategorySource == ai.SourceManual && tx.CategoryID != nil {
			if normCred := ai.NormalizeText(tx.CreditorName); normCred != "" {
				rules[normCred] = *tx.CategoryID
			}
			if normDesc := ai.NormalizeText(tx.Description); normDesc != "" {
				rules[normDesc] = *tx.CategoryID
			}
		}
	}
	return rules, nil
}

func (s *MemoryWorkerStore) ListCategories(_ context.Context) ([]ai.CategoryOption, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	out := make([]ai.CategoryOption, len(s.categories))
	copy(out, s.categories)
	return out, nil
}

func (s *MemoryWorkerStore) ApplySyncOutcome(_ context.Context, outcome SyncOutcome) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	affectedPeriods := make(map[string]bool)

	// 1. Delete disappeared pending transactions
	for _, delID := range outcome.DeletedPendingIDs {
		delete(s.transactions, delID)
	}

	// 2. Increment pending_sync_count on still-pending transactions
	for _, incID := range outcome.IncrementedPendingIDs {
		if tx, ok := s.transactions[incID]; ok {
			tx.PendingSyncCount++
		}
	}

	// 3. Promote pending transactions that became booked
	for storedID, promoted := range outcome.PromotedPendingToBook {
		if tx, ok := s.transactions[storedID]; ok {
			tx.GoCardlessTransactionID = promoted.Incoming.GoCardlessTransactionID
			tx.Date = promoted.Incoming.Date
			tx.AmountCents = promoted.Incoming.AmountCents
			tx.Description = promoted.Incoming.Description
			tx.CreditorName = promoted.Incoming.CreditorName
			tx.CategoryID = promoted.CategoryID
			tx.CategorySource = promoted.CategorySource
			tx.IsInternalTransfer = promoted.IsInternalTransfer
			tx.IsPending = false
			tx.PendingSyncCount = 0
			affectedPeriods[tx.Date.Format("2006-01")] = true
		}
	}

	// 4. Insert genuinely new transactions
	for _, nt := range outcome.NewTransactions {
		id := genID()
		s.transactions[id] = &storedTxRecord{
			UserID:    outcome.UserID,
			AccountID: outcome.AccountID,
			StoredTransaction: dedup.StoredTransaction{
				ID:                      id,
				GoCardlessTransactionID: nt.Incoming.GoCardlessTransactionID,
				Date:                    nt.Incoming.Date,
				AmountCents:             nt.Incoming.AmountCents,
				Description:             nt.Incoming.Description,
				CreditorName:            nt.Incoming.CreditorName,
				CategoryID:              nt.CategoryID,
				CategorySource:          nt.CategorySource,
				IsInternalTransfer:      nt.IsInternalTransfer,
				IsPending:               nt.Incoming.IsPending,
				PendingSyncCount:        0,
			},
		}
		if !nt.Incoming.IsPending {
			affectedPeriods[nt.Incoming.Date.Format("2006-01")] = true
		}
	}

	// 5. Update account balance, last_sync_at, and per-endpoint rate limit headers
	if acc, ok := s.accounts[outcome.AccountID]; ok {
		acc.BalanceCents = outcome.BalanceCents
		acc.LastSyncAt = outcome.CompletedAt
		acc.TransactionsRateLimits = outcome.TransactionsRateLimits
		acc.BalancesRateLimits = outcome.BalancesRateLimits
		if outcome.TransactionsRateLimits.Limit > 0 {
			acc.RemainingCalls = outcome.TransactionsRateLimits.Remaining
		}
	}

	// 6. Recompute pre-aggregated spending_summaries for affected periods
	for period := range affectedPeriods {
		s.recomputePeriodSummaryLocked(outcome.UserID, period)
	}

	if outcome.SyncID != "" {
		s.syncStatuses[outcome.SyncID] = "success"
	}

	return nil
}

func (s *MemoryWorkerStore) recomputePeriodSummaryLocked(userID, period string) {
	var totalIncome, totalExpenses int64
	byCat := make(map[string]*CategorySummaryItem)

	for _, tx := range s.transactions {
		if tx.UserID != userID || tx.IsPending {
			continue
		}
		if tx.Date.Format("2006-01") != period {
			continue
		}

		isTransfer := tx.IsInternalTransfer || (tx.CategoryID != nil && *tx.CategoryID == "cat_transfers")
		if !isTransfer {
			if tx.AmountCents > 0 {
				totalIncome += tx.AmountCents
			} else if tx.AmountCents < 0 {
				totalExpenses += (-tx.AmountCents)
			}
		}

		if tx.CategoryID != nil && *tx.CategoryID != "" {
			catID := *tx.CategoryID
			item, ok := byCat[catID]
			if !ok {
				item = &CategorySummaryItem{CategoryID: catID}
				byCat[catID] = item
			}
			item.TotalCents += tx.AmountCents
			item.Count++
		}
	}

	catSlice := make([]CategorySummaryItem, 0, len(byCat))
	for _, item := range byCat {
		catSlice = append(catSlice, *item)
	}

	s.summaries[userID+"|"+period] = &SpendingSummaryRecord{
		UserID:        userID,
		Period:        period,
		TotalIncome:   totalIncome,
		TotalExpenses: totalExpenses,
		ByCategory:    catSlice,
		UpdatedAt:     time.Now().UTC(),
	}
}

func (s *MemoryWorkerStore) MarkSyncFailed(_ context.Context, syncID string, _ int, _ string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if syncID != "" {
		s.syncStatuses[syncID] = "failed"
	}
	return nil
}

func (s *MemoryWorkerStore) EvaluateAndCreateBudgetAlerts(_ context.Context, userID, period string) ([]AlertRecord, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	sum, ok := s.summaries[userID+"|"+period]
	if !ok {
		return nil, nil
	}

	spentByCat := make(map[string]int64)
	for _, c := range sum.ByCategory {
		if c.TotalCents < 0 {
			spentByCat[c.CategoryID] = -c.TotalCents
		}
	}

	var created []AlertRecord
	for _, b := range s.budgets {
		if b.UserID != userID || b.Amount <= 0 {
			continue
		}
		spent := spentByCat[b.CategoryID]
		pct := math.Round((float64(spent)/float64(b.Amount))*10000) / 100

		var alertType, msg string
		if spent >= b.Amount {
			alertType = "budget_exceeded"
			msg = fmt.Sprintf("You have exceeded your %s budget", b.CategoryID)
		} else if pct >= 80.0 {
			alertType = "budget_threshold"
			msg = fmt.Sprintf("You have reached 80%% of your %s budget", b.CategoryID)
		} else {
			continue
		}

		budgetID := b.ID
		if s.alertExistsLocked(userID, &budgetID, nil, alertType, period) {
			continue
		}
		rec := AlertRecord{
			ID:        genID(),
			UserID:    userID,
			BudgetID:  &budgetID,
			Type:      alertType,
			Period:    period,
			Message:   msg,
			CreatedAt: time.Now().UTC(),
			Metadata: map[string]any{
				"budget_id":   b.ID,
				"category_id": b.CategoryID,
				"percentage":  pct,
				"spent":       spent,
				"limit":       b.Amount,
			},
		}
		s.alerts[rec.ID] = &rec
		created = append(created, rec)
	}

	return created, nil
}

func (s *MemoryWorkerStore) CreateConsentAlert(_ context.Context, userID, accountID, alertType, period, message string) (*AlertRecord, bool, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	accID := accountID
	if s.alertExistsLocked(userID, nil, &accID, alertType, period) {
		return nil, false, nil
	}
	rec := AlertRecord{
		ID:        genID(),
		UserID:    userID,
		AccountID: &accID,
		Type:      alertType,
		Period:    period,
		Message:   message,
		CreatedAt: time.Now().UTC(),
	}
	s.alerts[rec.ID] = &rec
	return &rec, true, nil
}

func (s *MemoryWorkerStore) alertExistsLocked(userID string, budgetID, accountID *string, alertType, period string) bool {
	val := func(p *string) string {
		if p == nil {
			return ""
		}
		return *p
	}
	for _, a := range s.alerts {
		if a.UserID == userID &&
			val(a.BudgetID) == val(budgetID) &&
			val(a.AccountID) == val(accountID) &&
			a.Type == alertType &&
			a.Period == period {
			return true
		}
	}
	return false
}

func (s *MemoryWorkerStore) ListUncategorizedBooked(_ context.Context) ([]UncategorizedTransaction, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	var out []UncategorizedTransaction
	for _, tx := range s.transactions {
		if !tx.IsPending && tx.CategoryID == nil {
			out = append(out, UncategorizedTransaction{
				ID:          tx.ID,
				UserID:      tx.UserID,
				AccountID:   tx.AccountID,
				Date:        tx.Date,
				Description: tx.Description,
				Creditor:    tx.CreditorName,
				AmountCents: tx.AmountCents,
			})
		}
	}
	return out, nil
}

func (s *MemoryWorkerStore) ApplyRetriedCategories(_ context.Context, updates map[string]ai.ClassificationResult) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	affected := make(map[string]struct{ userID, period string })
	for txID, res := range updates {
		if res.CategoryID == nil {
			continue
		}
		if tx, ok := s.transactions[txID]; ok {
			tx.CategoryID = res.CategoryID
			tx.CategorySource = res.CategorySource
			key := tx.UserID + "|" + tx.Date.Format("2006-01")
			affected[key] = struct{ userID, period string }{tx.UserID, tx.Date.Format("2006-01")}
		}
	}
	for _, up := range affected {
		s.recomputePeriodSummaryLocked(up.userID, up.period)
	}
	return nil
}
